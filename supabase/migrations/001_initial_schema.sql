-- TraceCare MVP: minimal encounter storage for the synthetic-data public demo.
-- Mirrors backend/app/storage/database.py (the backend also runs CREATE TABLE IF NOT EXISTS on startup).
-- Do NOT store real patient data.

create table if not exists public.encounters (
    id                varchar(36) primary key,          -- UUID string generated by the backend
    created_at        timestamptz not null default now(),
    language          varchar(16) not null default 'en',
    template_id       text,
    template_version  text,
    provider          varchar(32) not null,             -- 'demo' or 'anthropic'
    transcript_text   text,                             -- intentionally left NULL by the backend
    analysis_result   jsonb not null,                   -- segments, facts, evidence, coverage, outputs
    review_status     varchar(32) not null default 'provisional_review_required'
);

create index if not exists encounters_created_at_idx on public.encounters (created_at desc);

-- All access goes through FastAPI using the server-side DATABASE_URL.
-- Enable RLS with no policies so the table is not readable/writable through Supabase's Data API
-- (anon / authenticated roles). The backend's postgres role bypasses RLS.
alter table public.encounters enable row level security;
revoke all on table public.encounters from anon, authenticated;

