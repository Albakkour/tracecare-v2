"""Sample transcripts: hand-written synthetic examples plus a few role-played ACI-Bench encounters.

Generated by scripts/build_samples.py. ACI-Bench conversations are role-played (no real patients)
and are redistributed under the dataset's license with attribution.
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

SAMPLES_PATH = Path(__file__).resolve().parent.parent / "samples" / "samples.json"


@lru_cache
def load_samples() -> list[dict]:
    if not SAMPLES_PATH.exists():
        return []
    return json.loads(SAMPLES_PATH.read_text(encoding="utf-8"))["samples"]


EVALUATION_DIR = Path(__file__).resolve().parent.parent / "evaluation"


@lru_cache
def _data() -> dict:
    if not SAMPLES_PATH.exists():
        return {}
    return json.loads(SAMPLES_PATH.read_text(encoding="utf-8"))


def list_records() -> list[dict]:
    return _data().get("records", [])


def evaluation_results() -> dict:
    out = {}
    for name in ("aci", "plaba"):
        path = EVALUATION_DIR / f"{name}.json"
        out[name] = json.loads(path.read_text(encoding="utf-8")) if path.exists() else None
    return out


def list_samples() -> list[dict]:
    return [{k: v for k, v in s.items() if k not in {"transcript", "reference_note"}} for s in load_samples()]


def get_sample(sample_id: str) -> dict | None:
    return next((s for s in load_samples() if s["sample_id"] == sample_id), None)
